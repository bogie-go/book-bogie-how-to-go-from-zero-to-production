#!/usr/bin/env bash
# guard-generated.sh: refuse hand edits to files Bogie and sqlc generate,
# and say which command to run instead. Claude Code runs it before every
# Edit or Write; exit 2 blocks the edit and sends stderr back to Claude.

if ! command -v jq >/dev/null; then
  echo "guard-generated.sh needs jq to read the edit; install jq, then try again" >&2
  exit 2
fi

input=$(cat)
file=$(jq -r '.tool_input.file_path // empty' <<<"$input")
tool=$(jq -r '.tool_name // empty' <<<"$input")
[ -z "$file" ] && exit 0
rel=${file#"$CLAUDE_PROJECT_DIR"/}

refuse() {
  echo "$1" >&2
  exit 2
}

# 1. sqlc's output: regenerated from db/queries on every `make sqlc`.
case "$rel" in
  db/sqlc/*)
    refuse "$rel is generated by sqlc. Change the SQL in db/queries (your own queries go in a *_extra.sql file), then run: make sqlc"
    ;;
esac

# 2. Files a Bogie generator owns under db/: they say so near the top.
case "$rel" in
  db/*)
    if [ -f "$file" ] && head -n 40 "$file" | grep -q "overwritten whole on the next run"; then
      refuse "$rel is written by a Bogie generator and overwritten on the next run. Put your code in the *_extra file beside it (for example db/adapter/products_extra.go or db/queries/products_extra.sql). To change a table, run: bogie g migration <name> <column:type>..., then bogie model:sync [TABLE]"
    fi
    ;;
esac

# 3. New migrations come from the generator, so their names and timestamps are right.
case "$rel" in
  db/migrate/*)
    if [ "$tool" = "Write" ] && [ ! -f "$file" ]; then
      refuse "Create migrations with the generator, then edit the file it writes: bogie g migration <name> <column:type>..."
    fi
    ;;
esac

exit 0
